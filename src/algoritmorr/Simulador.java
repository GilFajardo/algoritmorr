    public void Ingresar(String rafaga){ //Ingresar proceso a la tabla
        DefaultTableModel modelo=(DefaultTableModel) jTIngreso.getModel();

        Contador ++;
        Object[] miTabla = new Object[5];
        miTabla[0]= Contador;
        miTabla[1]= rafaga;
        //miTabla[1]= jTFCapturaRafaga.getText();
        miTabla[2]= Quantum;
        //miTabla[2]= jTFCapturaQuantum.getText();
        miTabla[3]= rafaga;
        miTabla[4]= "Listo";
        modelo.addRow(miTabla);
        jTIngreso.setModel(modelo);
    }
    
    public void Cargar(int i){
        NProceso = (int) jTIngreso.getValueAt(i, 0);

        Object rafagaObj = jTIngreso.getValueAt(i, 1);
        if (rafagaObj instanceof String) {
            Rafaga = parseInt((String) rafagaObj);
        } else if (rafagaObj instanceof Integer) {
            Rafaga = (Integer) rafagaObj;
        }

        Object quantumObj = jTIngreso.getValueAt(i, 2);
        if (quantumObj instanceof String) {
            Quantum = parseInt((String) quantumObj);
        } else if (quantumObj instanceof Integer) {
            Quantum = (Integer) quantumObj;
        }

        Object residuoRafagaObj = jTIngreso.getValueAt(i, 3);
        if (residuoRafagaObj instanceof String) {
            ResiduoRafaga = parseInt((String) residuoRafagaObj);
        } else if (residuoRafagaObj instanceof Integer) {
            ResiduoRafaga = (Integer) residuoRafagaObj;
        }
    }

    
    public void Informe(int c){
    DefaultTableModel modelo2 = (DefaultTableModel) jTFinal.getModel();

    Object[] miTabla= new Object[5];
    miTabla[0]= c+1;
    miTabla[1]= Rafaga;
    miTabla[2]= Quantum;
    miTabla[3]= TiempoProceso+" Segundos";
    miTabla[4]= "Terminado";
    modelo2.addRow(miTabla);
    jTFinal.setModel(modelo2);

    CantidadProcesos++;
    //jLCantidadProcesos.setText(String.valueOf(CantidadProcesos+" Terminados"));
    //jLCantidadTiempo.setText(String.valueOf(TiempoProceso+" Segundos"));
}
    
    public void Borrar(int c){ //Elimina los registros de la tabla procesos
    jTIngreso.setValueAt(0,c,0);
    jTIngreso.setValueAt("0",c,1);
    jTIngreso.setValueAt("0",c,2);
    jTIngreso.setValueAt("0",c,3);
    jTIngreso.setValueAt("******",c,4);
}   

